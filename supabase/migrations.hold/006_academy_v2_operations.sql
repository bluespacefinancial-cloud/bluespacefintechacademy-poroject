CREATE TABLE IF NOT EXISTS public.clinics (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title varchar(200) NOT NULL,
  description text,
  mentor_id bigint NOT NULL REFERENCES public.users(id),
  cohort_id bigint REFERENCES public.cohorts(id) ON DELETE SET NULL,
  starts_at timestamptz NOT NULL,
  ends_at timestamptz NOT NULL,
  meet_url varchar(500),
  capacity int NOT NULL DEFAULT 15 CHECK (capacity > 0),
  status varchar(20) NOT NULL DEFAULT 'scheduled'
    CHECK (status IN ('scheduled', 'live', 'completed', 'cancelled')),
  created_by bigint NOT NULL REFERENCES public.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (ends_at > starts_at)
);

CREATE TABLE IF NOT EXISTS public.clinic_bookings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id bigint NOT NULL REFERENCES public.clinics(id) ON DELETE CASCADE,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  status varchar(20) NOT NULL DEFAULT 'booked'
    CHECK (status IN ('booked', 'attended', 'cancelled')),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (clinic_id, user_id)
