CREATE POLICY "users view own profile or staff view profiles"
  ON public.users FOR SELECT
  USING (id = public.current_profile_id()
    OR public.current_profile_role() IN ('Instructor', 'Administrator'));

CREATE POLICY "users update own profile"
  ON public.users FOR UPDATE
  USING (id = public.current_profile_id())
  WITH CHECK (id = public.current_profile_id());

CREATE POLICY "staff manage enrolments"
  ON public.enrolments FOR ALL
  USING (public.current_profile_role() = 'Administrator')
  WITH CHECK (public.current_profile_role() = 'Administrator');

CREATE POLICY "students view own enrolments"
  ON public.enrolments FOR SELECT
  USING (user_id = public.current_profile_id());

CREATE POLICY "academy users view published modules"
  ON public.modules FOR SELECT
  USING (is_published OR public.current_profile_role() IN ('Instructor', 'Administrator'));

CREATE POLICY "academy staff manage modules"
  ON public.modules FOR ALL
  USING (public.current_profile_role() IN ('Instructor', 'Administrator'))
  WITH CHECK (public.current_profile_role() IN ('Instructor', 'Administrator'));

CREATE POLICY "academy users view lessons for visible modules"
  ON public.lessons FOR SELECT
  USING (
    EXISTS (
      SELECT 1 FROM public.modules m
      WHERE m.id = lessons.module_id
        AND (m.is_published OR public.current_profile_role() IN ('Instructor', 'Administrator'))
    )
  );

CREATE POLICY "academy staff manage lessons"
  ON public.lessons FOR ALL
