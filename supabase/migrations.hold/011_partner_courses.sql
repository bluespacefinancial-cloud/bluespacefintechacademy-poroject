  USING (is_published AND EXISTS (
    SELECT 1 FROM public.partner_courses c
    WHERE c.id = course_id AND c.status = 'published'
      AND EXISTS (
        SELECT 1 FROM public.enrolments e
        WHERE e.user_id = public.current_profile_id()
          AND e.status IN ('enrolled', 'active', 'completed')
          AND (c.cohort_id IS NULL OR e.cohort_id = c.cohort_id)
          AND (c.track IS NULL OR c.track = 'All' OR e.track = c.track)
      )
  ));

