-- Enable UUID extension
-- We'll use bigint for IDs to keep compatibility with existing patterns

-- ===================== TABLES =====================

CREATE TABLE public.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(191) DEFAULT NULL,
  email varchar(191) NOT NULL UNIQUE,
  password varchar(191) DEFAULT NULL,
  type varchar(20) DEFAULT NULL CHECK (type IN ('Student', 'Instructor', 'Administrator')),
  avatar varchar(191) NOT NULL DEFAULT 'avatar.png',
  phone varchar(191) DEFAULT NULL,
  is_active int NOT NULL DEFAULT 1,
  force_password_change smallint NOT NULL DEFAULT 0,
  last_login_at timestamptz DEFAULT NULL,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- Cohorts: quarterly intakes (Dec 2026, Mar 2027, Jun 2027, Sep 2027)
CREATE TABLE public.cohorts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL, -- e.g. "Cohort 1 - December 2026"
  track_finsoft boolean NOT NULL DEFAULT true,
  track_finops boolean NOT NULL DEFAULT true,
  capacity int NOT NULL DEFAULT 40,
  start_date date NOT NULL,
  end_date date NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'planned' CHECK (status IN ('planned', 'active', 'completed', 'archived')),
  created_by bigint NOT NULL DEFAULT 0,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- Enrolments: link users to cohorts with track
CREATE TABLE public.enrolments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cohort_id bigint NOT NULL,
  user_id bigint NOT NULL,
  track varchar(20) NOT NULL CHECK (track IN ('Finsoft', 'Finops')),
  status varchar(20) NOT NULL DEFAULT 'enrolled' CHECK (status IN ('enrolled', 'active', 'completed', 'withdrawn', 'suspended')),
  squad_id bigint DEFAULT NULL,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- Squads: mixed-track groups of 5-7 Fellows
CREATE TABLE public.squads (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cohort_id bigint NOT NULL,
  name varchar(100) NOT NULL, -- e.g. "Squad Alpha"
  squad_lead_id bigint DEFAULT NULL,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- Modules: course modules within the four-stage framework
CREATE TABLE public.modules (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cohort_id bigint NOT NULL,
  title varchar(200) NOT NULL,
  stage varchar(20) NOT NULL CHECK (stage IN ('foundations', 'domain_immersion', 'live_projects', 'certification')),
  domain varchar(20) CHECK (domain IN ('FaaS', 'FinCore', 'FinOps', 'FinInfra')),
  track varchar(20) CHECK (track IN ('Finsoft', 'Finops', 'All')),
  description text,
  week_start int NOT NULL,
  week_end int NOT NULL,
  is_published boolean NOT NULL DEFAULT false,
  created_by bigint NOT NULL DEFAULT 0,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- Lessons: individual lessons within modules
CREATE TABLE public.lessons (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  module_id bigint NOT NULL,
  title varchar(200) NOT NULL,
  type varchar(20) NOT NULL CHECK (type IN ('concept', 'demonstration', 'video', 'audio', 'lab', 'assessment', 'clinic', 'standup', 'sprint_review', 'retrospective')),
  duration_minutes int NOT NULL DEFAULT 60,
  content_url varchar(500), -- link to reading or external resource
  video_url varchar(500), -- Supabase storage signed URL for video lessons
  audio_url varchar(500), -- Supabase storage signed URL for audio lessons
  thumbnail_url varchar(500), -- lesson thumbnail image
  caption_url varchar(500), -- .vtt caption file URL
  is_required boolean NOT NULL DEFAULT true,
  order_index int NOT NULL DEFAULT 0,
  created_by bigint NOT NULL DEFAULT 0,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- Labs: guided lab assignments
CREATE TABLE public.labs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lesson_id bigint NOT NULL,
  title varchar(200) NOT NULL,
  instructions text NOT NULL,
  starter_code text,
  solution_code text,
  due_date timestamptz DEFAULT NULL,
  max_score int NOT NULL DEFAULT 100,
  track_specific boolean NOT NULL DEFAULT false,
  created_by bigint NOT NULL DEFAULT 0,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- Assessments: quizzes, domain assessments, capstone
CREATE TABLE public.assessments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  module_id bigint NOT NULL,
  title varchar(200) NOT NULL,
  type varchar(20) NOT NULL CHECK (type IN ('quiz', 'domain_assessment', 'capstone', 'peer_review', 'mentor_evaluation')),
  weight decimal(5,2) NOT NULL DEFAULT 0, -- percentage weight in final grade
  max_score int NOT NULL DEFAULT 100,
  pass_mark int NOT NULL DEFAULT 70,
  due_date timestamptz DEFAULT NULL,
  is_published boolean NOT NULL DEFAULT false,
  created_by bigint NOT NULL DEFAULT 0,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- Submissions: student submissions for labs and assessments
CREATE TABLE public.submissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL,
  lab_id bigint DEFAULT NULL,
  assessment_id bigint DEFAULT NULL,
  squad_id bigint DEFAULT NULL,
  status varchar(20) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'submitted', 'graded', 'remediation', 'passed', 'failed')),
  content_url varchar(500), -- link to submitted work (GitHub, sandbox, etc.)
  score int DEFAULT NULL,
  feedback text,
  graded_by bigint DEFAULT NULL,
  graded_at timestamptz DEFAULT NULL,
  submitted_at timestamptz DEFAULT now(),
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- Lesson progress: track watch time and completion per user per lesson
CREATE TABLE public.lesson_progress (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL,
  lesson_id bigint NOT NULL,
  watch_time_seconds int NOT NULL DEFAULT 0,
  completion_percentage decimal(5,2) NOT NULL DEFAULT 0,
  is_completed boolean NOT NULL DEFAULT false,
  last_position_seconds int NOT NULL DEFAULT 0,
  completed_at timestamptz DEFAULT NULL,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  UNIQUE(user_id, lesson_id)
);

-- Use cases: live Factory problems for project stage
CREATE TABLE public.use_cases (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cohort_id bigint NOT NULL,
  domain varchar(20) NOT NULL CHECK (domain IN ('FaaS', 'FinCore', 'FinOps', 'FinInfra')),
  title varchar(200) NOT NULL,
  description text NOT NULL,
  stakeholder varchar(200),
  sandbox_access boolean NOT NULL DEFAULT false,
  anonymised_data boolean NOT NULL DEFAULT true,
  confidentiality_terms text,
  status varchar(20) NOT NULL DEFAULT 'proposed' CHECK (status IN ('proposed', 'qualified', 'assigned', 'completed', 'archived')),
  created_by bigint NOT NULL DEFAULT 0,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- Sprints: 2-week sprints within live projects
CREATE TABLE public.sprints (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  use_case_id bigint NOT NULL,
  squad_id bigint NOT NULL,
  sprint_number int NOT NULL CHECK (sprint_number IN (1, 2, 3)),
  start_date date NOT NULL,
  end_date date NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'planned' CHECK (status IN ('planned', 'active', 'completed')),
  uat_completed boolean NOT NULL DEFAULT false,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- Certifications: Fellow certification records
CREATE TABLE public.certifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL,
  cohort_id bigint NOT NULL,
  track varchar(20) NOT NULL CHECK (track IN ('Finsoft', 'Finops')),
  status varchar(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'certified', 'remediation', 'deferred')),
  final_grade decimal(5,2) DEFAULT NULL,
  attendance_percentage decimal(5,2) DEFAULT NULL,
  certificate_url varchar(500),
  skills_profile jsonb DEFAULT '{}',
  panel_review_date timestamptz DEFAULT NULL,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- Placements: project placements after certification
CREATE TABLE public.placements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  certification_id bigint NOT NULL,
  user_id bigint NOT NULL,
  role varchar(50) NOT NULL CHECK (role IN ('Project Manager', 'Field Lead', 'UAT', 'Technical Specialist')),
  project_id varchar(200),
  start_date date,
  status varchar(20) NOT NULL DEFAULT 'matched' CHECK (status IN ('matched', 'interviewing', 'placed', 'completed')),
  checkin_30_days timestamptz DEFAULT NULL,
  checkin_60_days timestamptz DEFAULT NULL,
  checkin_90_days timestamptz DEFAULT NULL,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- Notifications: in-app notifications
CREATE TABLE public.notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL,
  type text NOT NULL,
  data text NOT NULL,
  is_read smallint NOT NULL DEFAULT 0,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- Audit logs: admin audit trail
CREATE TABLE public.audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint DEFAULT NULL,
  user_name varchar(191) DEFAULT NULL,
  user_role varchar(20) DEFAULT NULL,
  action varchar(50) NOT NULL,
  entity_type varchar(50) DEFAULT NULL,
  entity_id bigint DEFAULT NULL,
  description text NOT NULL,
  metadata jsonb DEFAULT NULL,
  ip_address varchar(45) DEFAULT NULL,
  severity varchar(10) NOT NULL DEFAULT 'INFO',
  created_at timestamptz DEFAULT now()
);

