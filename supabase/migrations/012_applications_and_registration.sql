-- Public academy applications and administrator review workflow.
-- Run after migrations 001-011.

BEGIN;

CREATE TABLE IF NOT EXISTS public.academy_applications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_user_id uuid NOT NULL UNIQUE,
  user_id bigint REFERENCES public.users(id) ON DELETE SET NULL,
  name varchar(191) NOT NULL,
  email varchar(191) NOT NULL,
  phone varchar(191),
  requested_role varchar(20) NOT NULL CHECK (requested_role IN ('Student', 'Instructor', 'Partner')),
  track varchar(20) CHECK (track IN ('Finsoft', 'Finops')),
  organisation varchar(200),
  motivation text,
  status varchar(20) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'approved', 'rejected')),
  review_reason text,
  reviewed_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_academy_applications_status
  ON public.academy_applications(status, created_at DESC);

ALTER TABLE public.academy_applications ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "staff manage academy applications" ON public.academy_applications;
CREATE POLICY "staff manage academy applications"
  ON public.academy_applications FOR ALL
  USING (public.current_profile_role() = 'Administrator')
  WITH CHECK (public.current_profile_role() = 'Administrator');

DROP POLICY IF EXISTS "applicants view own application" ON public.academy_applications;
CREATE POLICY "applicants view own application"
  ON public.academy_applications FOR SELECT
  USING (auth_user_id = auth.uid());

CREATE OR REPLACE FUNCTION public.review_academy_application(
  p_application_id bigint,
  p_decision varchar,
  p_cohort_id bigint DEFAULT NULL,
  p_track varchar DEFAULT NULL,
  p_reason text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  application_row public.academy_applications%ROWTYPE;
  reviewer_id bigint;
BEGIN
  IF public.current_profile_role() <> 'Administrator' THEN
    RAISE EXCEPTION 'Administrator access required';
  END IF;
  IF p_decision NOT IN ('approved', 'rejected') THEN
    RAISE EXCEPTION 'Invalid application decision';
  END IF;

  SELECT * INTO application_row
  FROM public.academy_applications
  WHERE id = p_application_id
  FOR UPDATE;

  IF application_row.id IS NULL THEN
    RAISE EXCEPTION 'Application not found';
  END IF;
  IF application_row.status <> 'pending' THEN
    RAISE EXCEPTION 'Application has already been reviewed';
  END IF;
  IF application_row.requested_role = 'Student'
     AND p_decision = 'approved'
     AND (p_cohort_id IS NULL OR p_track IS NULL) THEN
    RAISE EXCEPTION 'Approved student applications require a cohort and track';
  END IF;
  IF p_track IS NOT NULL AND p_track NOT IN ('Finsoft', 'Finops') THEN
    RAISE EXCEPTION 'Invalid track';
  END IF;

  reviewer_id := public.current_profile_id();

  UPDATE public.academy_applications
  SET status = p_decision,
      review_reason = NULLIF(trim(p_reason), ''),
      reviewed_by = reviewer_id,
      reviewed_at = now(),
      updated_at = now()
  WHERE id = application_row.id;

  UPDATE public.users
  SET is_active = CASE WHEN p_decision = 'approved' THEN 1 ELSE 0 END,
      updated_at = now()
  WHERE auth_user_id = application_row.auth_user_id
     OR lower(email) = lower(application_row.email);

  IF p_decision = 'approved' AND application_row.requested_role = 'Student' THEN
    INSERT INTO public.enrolments (cohort_id, user_id, track, status)
    SELECT p_cohort_id, u.id, p_track, 'enrolled'
    FROM public.users u
    WHERE u.auth_user_id = application_row.auth_user_id
       OR lower(u.email) = lower(application_row.email)
    ON CONFLICT DO NOTHING;
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.review_academy_application(bigint, varchar, bigint, varchar, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.review_academy_application(bigint, varchar, bigint, varchar, text) TO authenticated;

COMMIT;
