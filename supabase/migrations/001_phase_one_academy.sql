CREATE POLICY "academy staff manage live classes"
  ON public.live_classes FOR ALL
  USING (public.current_profile_role() IN ('Instructor', 'Administrator'))
  WITH CHECK (public.current_profile_role() IN ('Instructor', 'Administrator'));

CREATE POLICY "students view cohort classes"
  ON public.live_classes FOR SELECT
  USING (
    visibility = 'cohort'
    AND EXISTS (
      SELECT 1
      FROM public.enrolments e
      WHERE e.user_id = public.current_profile_id()
        AND e.cohort_id = live_classes.cohort_id
        AND e.status IN ('enrolled', 'active', 'completed')
    )
  );

CREATE POLICY "academy staff manage attendance"
  ON public.live_class_attendance FOR ALL
  USING (public.current_profile_role() IN ('Instructor', 'Administrator'))
  WITH CHECK (public.current_profile_role() IN ('Instructor', 'Administrator'));

CREATE POLICY "students view own attendance"
  ON public.live_class_attendance FOR SELECT
  USING (user_id = public.current_profile_id());

CREATE POLICY "users manage own google integration"
  ON public.google_integrations FOR ALL
  USING (user_id = public.current_profile_id())
  WITH CHECK (
    user_id = public.current_profile_id()
    AND public.current_profile_role() IN ('Instructor', 'Administrator')
  );

