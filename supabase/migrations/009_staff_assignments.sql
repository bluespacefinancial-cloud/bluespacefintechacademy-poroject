-- Instructor assignment boundaries.
-- Run after migrations 001-008.

CREATE TABLE IF NOT EXISTS public.instructor_cohort_assignments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instructor_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  cohort_id bigint NOT NULL REFERENCES public.cohorts(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (instructor_id, cohort_id)
);

CREATE TABLE IF NOT EXISTS public.instructor_squad_assignments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instructor_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  squad_id bigint NOT NULL REFERENCES public.squads(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (instructor_id, squad_id)
);

ALTER TABLE public.instructor_cohort_assignments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.instructor_squad_assignments ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "administrators manage instructor assignments" ON public.instructor_cohort_assignments;
DROP POLICY IF EXISTS "staff view own cohort assignments" ON public.instructor_cohort_assignments;
DROP POLICY IF EXISTS "administrators manage instructor squad assignments" ON public.instructor_squad_assignments;
DROP POLICY IF EXISTS "staff view own squad assignments" ON public.instructor_squad_assignments;

CREATE POLICY "administrators manage instructor assignments"
  ON public.instructor_cohort_assignments FOR ALL
  USING (public.current_profile_role() = 'Administrator')
  WITH CHECK (public.current_profile_role() = 'Administrator');
CREATE POLICY "staff view own cohort assignments"
  ON public.instructor_cohort_assignments FOR SELECT
  USING (instructor_id = public.current_profile_id() OR public.current_profile_role() = 'Administrator');
CREATE POLICY "administrators manage instructor squad assignments"
  ON public.instructor_squad_assignments FOR ALL
  USING (public.current_profile_role() = 'Administrator')
  WITH CHECK (public.current_profile_role() = 'Administrator');
CREATE POLICY "staff view own squad assignments"
  ON public.instructor_squad_assignments FOR SELECT
  USING (instructor_id = public.current_profile_id() OR public.current_profile_role() = 'Administrator');

CREATE INDEX IF NOT EXISTS idx_instructor_cohort_assignments_instructor
  ON public.instructor_cohort_assignments (instructor_id);
CREATE INDEX IF NOT EXISTS idx_instructor_squad_assignments_instructor
  ON public.instructor_squad_assignments (instructor_id);
