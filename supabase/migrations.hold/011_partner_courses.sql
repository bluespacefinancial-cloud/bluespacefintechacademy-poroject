CREATE POLICY "students view published partner courses" ON public.partner_courses FOR SELECT
  USING (
    status = 'published'
    AND EXISTS (
      SELECT 1 FROM public.enrolments e
      WHERE e.user_id = public.current_profile_id()
        AND e.status IN ('enrolled', 'active', 'completed')
        AND (partner_courses.cohort_id IS NULL OR e.cohort_id = partner_courses.cohort_id)
        AND (partner_courses.track IS NULL OR partner_courses.track = 'All' OR e.track = partner_courses.track)
    )
  );

