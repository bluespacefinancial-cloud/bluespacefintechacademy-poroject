-- BlueSPACE LMS Phase 1
-- Run after supabase/schema.sql and storage.sql.
-- This migration is for the free internal academy; it does not add commerce.

-- Supabase Auth uses UUIDs while the legacy profile tables use bigint IDs.
-- Email is unique and is used only as the bridge until the profile migration
-- to auth_user_id is completed.
CREATE OR REPLACE FUNCTION public.current_profile_id()
RETURNS bigint
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT id FROM public.users WHERE lower(email) = lower(auth.email()) LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.current_profile_role()
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT type FROM public.users WHERE lower(email) = lower(auth.email()) LIMIT 1;
$$;

CREATE TABLE IF NOT EXISTS public.live_classes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title varchar(200) NOT NULL,
  description text,
  cohort_id bigint REFERENCES public.cohorts(id) ON DELETE SET NULL,
  module_id bigint REFERENCES public.modules(id) ON DELETE SET NULL,
  instructor_id bigint NOT NULL REFERENCES public.users(id),
  starts_at timestamptz NOT NULL,
  ends_at timestamptz NOT NULL,
  visibility varchar(20) NOT NULL DEFAULT 'private'
    CHECK (visibility IN ('private', 'cohort')),
  status varchar(20) NOT NULL DEFAULT 'scheduled'
    CHECK (status IN ('scheduled', 'live', 'completed', 'cancelled')),
  meet_url varchar(500),
  google_event_id varchar(255),
  recording_url varchar(500),
  notes text,
  created_by bigint NOT NULL REFERENCES public.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (ends_at > starts_at)
);

CREATE TABLE IF NOT EXISTS public.live_class_attendance (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  live_class_id bigint NOT NULL REFERENCES public.live_classes(id) ON DELETE CASCADE,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  joined_at timestamptz,
  left_at timestamptz,
  status varchar(20) NOT NULL DEFAULT 'invited'
    CHECK (status IN ('invited', 'attended', 'absent')),
  UNIQUE (live_class_id, user_id)
);

CREATE TABLE IF NOT EXISTS public.google_integrations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL UNIQUE REFERENCES public.users(id) ON DELETE CASCADE,
  provider varchar(30) NOT NULL DEFAULT 'google_workspace'
    CHECK (provider = 'google_workspace'),
  calendar_email varchar(255),
  access_token_encrypted text,
  refresh_token_encrypted text,
  token_expires_at timestamptz,
  scopes text[] NOT NULL DEFAULT ARRAY[]::text[],
  connected_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_live_classes_cohort ON public.live_classes (cohort_id);
CREATE INDEX IF NOT EXISTS idx_live_classes_starts_at ON public.live_classes (starts_at);
CREATE INDEX IF NOT EXISTS idx_live_class_attendance_user ON public.live_class_attendance (user_id);

ALTER TABLE public.live_classes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.live_class_attendance ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.google_integrations ENABLE ROW LEVEL SECURITY;

