-- 09_media_assets.sql
--
-- Apply after 08_column_grants.sql.
--
-- Phase C of the partner course upload work. Bytes live on the public disk
-- (storage/app/public/media/...); this table is the index of what was uploaded
-- and by whom. Rows are written only by Laravel's media endpoint while it is
-- switched to `service_role`; browser clients never read this table directly.
-- They receive the asset URL from the upload response and store it on the
-- course or lesson row.
--
-- Because 00_bootstrap.sql sets
--   ALTER DEFAULT PRIVILEGES ... GRANT ALL ON TABLES TO anon, authenticated,
-- every new table starts fully granted. As with 08_column_grants.sql, that is
-- revoked here so a signed-in client cannot read or write the asset index.

BEGIN;

CREATE TABLE IF NOT EXISTS public.media_assets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_profile_id bigint REFERENCES public.users(id) ON DELETE SET NULL,
  partner_id bigint REFERENCES public.partners(id) ON DELETE SET NULL,
  provider character varying(20) NOT NULL DEFAULT 'local',
  kind character varying(20) NOT NULL,
  storage_key text NOT NULL UNIQUE,
  url text NOT NULL,
  mime character varying(120) NOT NULL,
  bytes bigint NOT NULL DEFAULT 0,
  checksum character varying(64),
  original_name character varying(255),
  status character varying(20) NOT NULL DEFAULT 'ready',
  error text,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT media_assets_provider_check
    CHECK ((provider)::text = ANY (ARRAY['local'::text, 's3'::text, 'youtube'::text])),
  CONSTRAINT media_assets_kind_check
    CHECK ((kind)::text = ANY (ARRAY['video'::text, 'audio'::text, 'image'::text, 'caption'::text, 'transcript'::text, 'document'::text])),
  CONSTRAINT media_assets_status_check
    CHECK ((status)::text = ANY (ARRAY['uploading'::text, 'processing'::text, 'ready'::text, 'failed'::text])),
  CONSTRAINT media_assets_bytes_check CHECK (bytes >= 0)
);

CREATE INDEX IF NOT EXISTS media_assets_owner_idx ON public.media_assets (owner_profile_id);
CREATE INDEX IF NOT EXISTS media_assets_partner_idx ON public.media_assets (partner_id);
CREATE INDEX IF NOT EXISTS media_assets_kind_idx ON public.media_assets (kind);

ALTER TABLE public.media_assets ENABLE ROW LEVEL SECURITY;

-- Service-owned table: no browser access at all.
REVOKE ALL ON TABLE public.media_assets FROM anon, authenticated;

-- --------------------------------------------------- partner_course_lessons --
-- Uploaded assets need somewhere to point. `type` lets one lesson list hold
-- video, audio and text lessons; the rest mirror the academy `lessons` table so
-- the shared MediaPlayer can render both.
ALTER TABLE public.partner_course_lessons
  ADD COLUMN IF NOT EXISTS type character varying(20) NOT NULL DEFAULT 'video';

ALTER TABLE public.partner_course_lessons
  DROP CONSTRAINT IF EXISTS partner_course_lessons_type_check;
ALTER TABLE public.partner_course_lessons
  ADD CONSTRAINT partner_course_lessons_type_check
  CHECK ((type)::text = ANY (ARRAY['video'::text, 'audio'::text, 'text'::text]));

ALTER TABLE public.partner_course_lessons
  ADD COLUMN IF NOT EXISTS audio_url character varying;
ALTER TABLE public.partner_course_lessons
  ADD COLUMN IF NOT EXISTS duration_seconds integer;
ALTER TABLE public.partner_course_lessons
  ADD COLUMN IF NOT EXISTS thumbnail_url character varying;
ALTER TABLE public.partner_course_lessons
  ADD COLUMN IF NOT EXISTS caption_url character varying;

COMMIT;
