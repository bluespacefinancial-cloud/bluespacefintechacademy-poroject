ALTER TABLE public.users ADD COLUMN IF NOT EXISTS auth_user_id uuid UNIQUE;

CREATE OR REPLACE FUNCTION public.current_profile_id()
RETURNS bigint
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT id
  FROM public.users
  WHERE auth_user_id = auth.uid()
     OR (auth_user_id IS NULL AND lower(email) = lower(auth.email()))
  LIMIT 1;
$$;

CREATE TABLE IF NOT EXISTS public.announcements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title varchar(200) NOT NULL,
  content text NOT NULL,
  type varchar(30) NOT NULL DEFAULT 'announcement',
  audience varchar(30) NOT NULL DEFAULT 'all',
  author_id bigint NOT NULL REFERENCES public.users(id),
  pinned boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_announcements_created_at ON public.announcements (created_at DESC);
ALTER TABLE public.announcements ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "academy users view announcements" ON public.announcements;
DROP POLICY IF EXISTS "academy staff manage announcements" ON public.announcements;

CREATE POLICY "academy users view announcements"
  ON public.announcements FOR SELECT
  USING (
    audience = 'all'
    OR (audience = 'finsoft' AND EXISTS (
      SELECT 1 FROM public.enrolments e
      WHERE e.user_id = public.current_profile_id() AND e.track = 'Finsoft'
    ))
    OR (audience = 'finops' AND EXISTS (
      SELECT 1 FROM public.enrolments e
      WHERE e.user_id = public.current_profile_id() AND e.track = 'Finops'
    ))
  );

CREATE POLICY "academy staff manage announcements"
  ON public.announcements FOR ALL
  USING (public.current_profile_role() IN ('Instructor', 'Administrator'))
  WITH CHECK (
    public.current_profile_role() IN ('Instructor', 'Administrator')
    AND author_id = public.current_profile_id()
  );
